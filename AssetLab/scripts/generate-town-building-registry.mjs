import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateTownBuildingManifest } from "../src/town-building-generator.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const assetRoot = path.resolve(here, "..");
const repoRoot = path.resolve(assetRoot, "..");
const manifestPath = path.join(assetRoot, "town/town-building-generator-v1.json");
const outputPath = path.join(repoRoot, "Sources/VisualRuntime/TownBuildingVisualRegistry.generated.swift");
const manifestBytes = fs.readFileSync(manifestPath);
const manifest = validateTownBuildingManifest(JSON.parse(manifestBytes.toString("utf8")));
const manifestSHA256 = crypto.createHash("sha256").update(manifestBytes).digest("hex");
const entries = Object.entries(manifest.acceptedLayers)
  .map(([stationID, record]) => `        "${stationID}": "${record.file.replace(/\.png$/, "")}"`)
  .join(",\n");
const source = `// Generated by AssetLab/scripts/generate-town-building-registry.mjs. Do not hand-edit.\n` +
`import Foundation\n\n` +
`enum TownBuildingVisualRegistry {\n` +
`    static let generatorVersion = "${manifest.generatorVersion}"\n` +
`    static let sourceManifestSHA256 = "${manifestSHA256}"\n\n` +
`    private static let assetByStationID: [String: String] = [\n${entries}\n    ]\n\n` +
`    static func assetName(for stationID: StationID) -> String? {\n` +
`        assetByStationID[stationID.rawValue]\n` +
`    }\n` +
`}\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== source) throw new Error("TownBuildingVisualRegistry.generated.swift is stale; run npm run generate:town-registry");
  process.stdout.write(`town registry current: ${manifestSHA256}\n`);
} else {
  fs.writeFileSync(outputPath, source);
  process.stdout.write(`wrote ${outputPath}\nmanifest SHA-256 ${manifestSHA256}\n`);
}
